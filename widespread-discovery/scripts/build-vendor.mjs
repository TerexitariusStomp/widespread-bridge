// build-vendor.mjs — regenerate vendor/*.bundle.mjs from installed deps.
// Run after bumping nostr-tools / rss-parser / yaml in package.json.
// The bundles are committed so `wsd` runs with zero npm install.
import { build } from "esbuild";
import { readFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const ENTRIES = {
  "nostr-tools": `export * from "nostr-tools";`,
  "rss-parser": `export { default } from "rss-parser";`,
  "yaml": `export { parse, parseDocument, parseAllDocuments, stringify } from "yaml";`,
};

function depVersion(name) {
  try {
    const pkg = JSON.parse(
      readFileSync(join(root, "node_modules", name, "package.json"), "utf8")
    );
    return pkg.version;
  } catch {
    // hoisted to the workspace root
    try {
      const pkg = JSON.parse(
        readFileSync(join(root, "..", "node_modules", name, "package.json"), "utf8")
      );
      return pkg.version;
    } catch {
      return "?";
    }
  }
}

mkdirSync(join(root, "vendor"), { recursive: true });
for (const [name, contents] of Object.entries(ENTRIES)) {
  const banner = `// GENERATED by scripts/build-vendor.mjs — do not edit.\n// ${name}@${depVersion(name)} bundled for zero-install use.`;
  await build({
    stdin: { contents, resolveDir: root, loader: "js" },
    bundle: true,
    format: "esm",
    platform: "node",
    target: "node20",
    outfile: join(root, "vendor", `${name}.bundle.mjs`),
    banner: {
      js: `${banner}\nimport { createRequire as __wsdCreateRequire } from "node:module";\nconst require = __wsdCreateRequire(import.meta.url);`,
    },
    logLevel: "warning",
  });
  console.log(`vendor/${name}.bundle.mjs <- ${name}@${depVersion(name)}`);
}
