// sync-surfaces.mjs — regenerate deployment-boundary copies from canonical
// sources. watcher-web/ and watcher-extension/ must ship as self-contained
// directories (they can't import ../), so their shared files are GENERATED
// here — never edit a "// GENERATED" file by hand.
//
//   node scripts/sync-surfaces.mjs           regenerate all copies
//   node scripts/sync-surfaces.mjs --check   exit non-zero if any copy drifts
import { build } from "esbuild";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");
let drift = 0;

const sha = (s) => createHash("sha256").update(s).digest("hex").slice(0, 16);

function depVersion(name) {
  const pkg = JSON.parse(readFileSync(join(root, "node_modules", name, "package.json"), "utf8"));
  return pkg.version;
}

function emit(destRel, content) {
  const path = join(root, destRel);
  if (CHECK) {
    let cur = null;
    try { cur = readFileSync(path, "utf8"); } catch { /* missing */ }
    if (cur === content) console.log(`ok    ${destRel}`);
    else { console.error(`DRIFT ${destRel}`); drift++; }
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`wrote ${destRel}`);
  }
}

function copy(srcRel, destRel) {
  const src = readFileSync(join(root, srcRel), "utf8");
  emit(destRel,
    `// GENERATED by scripts/sync-surfaces.mjs — do not edit.\n` +
    `// Source: ${srcRel} @ sha256:${sha(src)}\n\n${src}`);
}

async function nostrBundle(destRel) {
  const res = await build({
    stdin: { contents: `export * from "nostr-tools";`, resolveDir: root, loader: "js" },
    bundle: true,
    format: "iife",
    globalName: "NostrTools",
    platform: "browser",
    write: false,
    logLevel: "warning",
  });
  const src = res.outputFiles[0].text;
  emit(destRel,
    `// GENERATED by scripts/sync-surfaces.mjs — do not edit.\n` +
    `// nostr-tools@${depVersion("nostr-tools")} browser bundle @ sha256:${sha(src)}\n\n${src}`);
}

// Markdown copy — the earn skill's canonical source is the bridge's
// .agents path (what agents discover when working this repo); the
// widespread-skills dir is the distribution surface (npx skills add,
// ClawHub, plugin marketplaces).
function copyMd(srcRel, destRel) {
  const src = readFileSync(join(root, srcRel), "utf8");
  emit(destRel,
    `<!-- GENERATED by scripts/sync-surfaces.mjs — do not edit.\n` +
    `Source: ${srcRel} @ sha256:${sha(src)} -->\n\n` +
    src.replace(/^<!-- CANONICAL[^>]*-->\n*/m, ""));
}

copyMd(".agents/skills/widespread/SKILL.md", "widespread-skills/skills/widespread/SKILL.md");
copyMd(".agents/skills/widespread/SKILL.md", "widespread-mcp/skills/widespread/SKILL.md");
copy("widespread-discovery/src/core.mjs", "watcher-web/core.mjs");
copy("widespread-discovery/src/proto.mjs", "watcher-web/proto.mjs");
await nostrBundle("watcher-web/nostr.bundle.js");
await nostrBundle("watcher-extension/nostr.bundle.js");

if (CHECK) {
  if (drift) {
    console.error(`\n${drift} generated file(s) out of sync — run: npm run sync`);
    process.exit(1);
  }
  console.log("\nall generated files in sync");
}
